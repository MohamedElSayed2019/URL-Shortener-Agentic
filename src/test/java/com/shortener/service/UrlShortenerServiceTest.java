package com.hcb.sc.load.shortener.service;

import com.hcb.sc.load.shortener.model.ShortUrl;
import com.hcb.sc.load.shortener.ratelimit.FixedWindowRateLimiter;
import com.hcb.sc.load.shortener.repository.InMemoryUrlRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.time.Duration;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

class UrlShortenerServiceTest {

    private UrlShortenerService service;

    @BeforeEach
    void setUp() {
        service = new UrlShortenerService(new InMemoryUrlRepository(), new FixedWindowRateLimiter(1000, 60_000));
    }

    @Test
    void createsShortUrlWithAutoGeneratedCode() {
        ShortUrl s = service.createShortUrl("https://example.com/path", null, null, "client1");
        assertNotNull(s.getCode());
        assertFalse(s.getCode().isBlank());
        assertEquals("https://example.com/path", s.getLongUrl());
        assertNull(s.getExpiresAt());
    }

    @Test
    void createsShortUrlWithCustomAlias() {
        ShortUrl s = service.createShortUrl("https://example.com/path", "my-brand", null, "client1");
        assertEquals("my-brand", s.getCode());
    }

    @Test
    void rejectsDuplicateCustomAlias() {
        service.createShortUrl("https://example.com/a", "dup-alias", null, "client1");
        assertThrows(UrlValidationException.class,
                () -> service.createShortUrl("https://example.com/b", "dup-alias", null, "client1"));
    }

    @Test
    void rejectsInvalidCustomAliasFormat() {
        assertThrows(UrlValidationException.class,
                () -> service.createShortUrl("https://example.com/a", "no", null, "client1")); // too short
        assertThrows(UrlValidationException.class,
                () -> service.createShortUrl("https://example.com/a", "has space", null, "client1"));
    }

    @Test
    void rejectsBlankLongUrl() {
        assertThrows(UrlValidationException.class, () -> service.createShortUrl("", null, null, "client1"));
    }

    @Test
    void rejectsNonHttpScheme() {
        assertThrows(UrlValidationException.class, () -> service.createShortUrl("ftp://example.com/file", null, null, "client1"));
    }

    @Test
    void rejectsMalformedUrl() {
        assertThrows(UrlValidationException.class, () -> service.createShortUrl("not a url", null, null, "client1"));
    }

    @Test
    void resolveAndRecordClickIncrementsCountAndReturnsLongUrl() {
        ShortUrl created = service.createShortUrl("https://example.com/target", null, null, "client1");
        ShortUrl resolved = service.resolveAndRecordClick(created.getCode(), "https://ref.com", "TestAgent");
        assertEquals("https://example.com/target", resolved.getLongUrl());
        assertEquals(1, resolved.getClickCount());
    }

    @Test
    void resolvingUnknownCodeThrowsNotFound() {
        assertThrows(NotFoundException.class, () -> service.resolveAndRecordClick("doesnotexist", null, null));
    }

    @Test
    void expiredLinkThrowsNotFoundOnResolve() {
        ShortUrl created = service.createShortUrl("https://example.com/temp", null, Duration.ofMillis(-1), "client1");
        assertTrue(created.isExpired());
        assertThrows(NotFoundException.class, () -> service.resolveAndRecordClick(created.getCode(), null, null));
    }

    @Test
    void analyticsReflectClicksAndReferrers() {
        ShortUrl created = service.createShortUrl("https://example.com/analytics", null, null, "client1");
        service.resolveAndRecordClick(created.getCode(), "https://a.com", "UA1");
        service.resolveAndRecordClick(created.getCode(), "https://b.com", "UA2");
        service.resolveAndRecordClick(created.getCode(), "https://a.com", "UA3");

        Map<String, Object> analytics = service.getAnalytics(created.getCode());
        assertEquals(3L, ((Number) analytics.get("totalClicks")).longValue());
        assertEquals(2L, ((Number) analytics.get("uniqueReferrers")).longValue());
    }

    @Test
    void rateLimiterBlocksExcessiveRequests() {
        UrlShortenerService limited = new UrlShortenerService(new InMemoryUrlRepository(), new FixedWindowRateLimiter(2, 60_000));
        limited.createShortUrl("https://example.com/1", null, null, "limited-client");
        limited.createShortUrl("https://example.com/2", null, null, "limited-client");
        assertThrows(RateLimitExceededException.class,
                () -> limited.createShortUrl("https://example.com/3", null, null, "limited-client"));
    }

    @Test
    void listAllReturnsCreatedLinks() {
        service.createShortUrl("https://example.com/1", null, null, "client1");
        service.createShortUrl("https://example.com/2", null, null, "client1");
        assertEquals(2, service.listAll().size());
    }
}
